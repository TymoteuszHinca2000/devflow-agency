import { createHash } from 'node:crypto'
import { readFile, readdir, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import { introspect, typescript } from '@supabase/typegen'
import { format, resolveConfig } from 'prettier'
import { createTestDatabase } from '../supabase/tests/helpers/database.mjs'

const target = new URL('../src/types/database.types.ts', import.meta.url)
const migrationsDirectory = new URL('../supabase/migrations/', import.meta.url)
const migrations = (await readdir(migrationsDirectory))
  .filter((file) => /^\d{14}_.+\.sql$/.test(file))
  .sort()
const hash = createHash('sha256')
for (const file of migrations) {
  hash.update(file + '\n')
  hash.update((await readFile(new URL(file, migrationsDirectory), 'utf8')).replaceAll('\r\n', '\n'))
}

const db = await createTestDatabase({ includeFixtures: false })
try {
  const metadata = await introspect(db, { includedSchemas: ['public'] })
  const generated = await typescript.generate(
    metadata,
    {},
    {
      cwd: process.cwd(),
      env: {},
      format: async (code) =>
        format(code, { ...(await resolveConfig(fileURLToPath(target))), parser: 'typescript' }),
    },
  )
  const contents = `// Generated by @supabase/typegen from supabase/migrations; do not edit.\n// Migration SHA-256: ${hash.digest('hex')}\n// Regenerate: npm run db:types\n\n${generated}`
  if (process.argv.includes('--check')) {
    const current = (await readFile(target, 'utf8')).replaceAll('\r\n', '\n')
    if (current !== contents) {
      console.error(
        'Database types differ from migrations. Run npm run db:types and review the diff.',
      )
      process.exitCode = 1
    } else {
      console.log(
        'Database types match all migrations (official Supabase generator, local PostgreSQL).',
      )
    }
  } else {
    await writeFile(target, contents, 'utf8')
    console.log(
      'Generated src/types/database.types.ts from local migrations without network or credentials.',
    )
  }
} finally {
  await db.close()
}
